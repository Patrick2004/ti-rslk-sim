"""Generate rslk_sim/regnames.py from TI's msp432p401r.h.

Usage:
    python tools/gen_regnames.py [path/to/msp432p401r.h]

The generated table maps every peripheral register address to a readable
name such as "P4.IFG" or "TIMER_A0.CCR[3]".  It is only used for log
messages and disassembly annotation, so a missing CCS install is harmless:
the checked-in regnames.py is used as-is.
"""
import os
import re
import sys

DEFAULT_HEADER = r"C:\ti\ccsv7\ccs_base\arm\include\msp432p401r.h"

# TI's BSD-3-Clause license requires keeping its copyright notice in derived files.
NOTICE = '''"""Register names for MSP432P401R (generated by tools/gen_regnames.py - do not edit).

Derived from msp432p401r.h:
Copyright (C) 2012 - 2017 Texas Instruments Incorporated - http://www.ti.com/
Redistributed under TI's BSD-3-Clause license; see THIRD_PARTY_NOTICES.md.
"""
'''
SIZES = {"uint8_t": 1, "uint16_t": 2, "uint32_t": 4}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse_fields(body):
    """Parse a struct body into [(offset, size, name)], handling unions."""
    fields = []
    off = 0
    i = 0
    tokens = body
    while i < len(tokens):
        m_union = re.match(r"\s*union\s*\{", tokens[i:])
        if m_union:
            # find the matching closing brace of the union
            depth = 0
            j = i + m_union.end() - 1
            while j < len(tokens):
                if tokens[j] == "{":
                    depth += 1
                elif tokens[j] == "}":
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            inner = tokens[i + m_union.end():j]
            first = re.search(r"(uint8_t|uint16_t|uint32_t)\s+(\w+)\s*(\[(\d+)\])?\s*;", inner)
            size = SIZES[first.group(1)]
            count = int(first.group(4)) if first.group(4) else 1
            for k in range(count):
                name = first.group(2) + (f"[{k}]" if first.group(3) else "")
                fields.append((off, size, name))
                off += size
            end = tokens.index(";", j)
            i = end + 1
            continue
        m = re.match(r"\s*(?:__IO|__I|__O|volatile|const|\s)*\s*(uint8_t|uint16_t|uint32_t)\s+(\w+)\s*(\[(\d+)\])?\s*;", tokens[i:])
        if m:
            size = SIZES[m.group(1)]
            count = int(m.group(4)) if m.group(4) else 1
            for k in range(count):
                if not m.group(2).startswith("RESERVED"):
                    name = m.group(2) + (f"[{k}]" if m.group(3) else "")
                    fields.append((off, size, name))
                off += size
            i += m.end()
            continue
        if tokens[i:].strip() == "":
            break
        i += 1
    return fields


def main():
    header = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_HEADER
    text = strip_comments(open(header, encoding="latin-1").read())

    structs = {}
    for m in re.finditer(r"typedef\s+struct\s*\{(.*?)\}\s*(\w+)\s*;", text, flags=re.S):
        body, name = m.group(1), m.group(2)
        if name in structs:
            continue
        # nested union bodies contain '}' so re-scan with brace matching
        start = m.start(1)
        depth = 1
        j = start
        while depth:
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
            j += 1
        body = text[start:j - 1]
        tail = re.match(r"\s*(\w+)\s*;", text[j:])
        if tail:
            structs[tail.group(1)] = parse_fields(body)

    bases = {"PERIPH_BASE": 0x40000000, "PERIPH_BASE2": 0xE0000000}
    for m in re.finditer(r"#define\s+(\w+_BASE)\s+\(\s*(PERIPH_BASE2?)\s*\+\s*(0x[0-9A-Fa-f]+)\s*\)", text):
        bases[m.group(1)] = bases[m.group(2)] + int(m.group(3), 16)
    for m in re.finditer(r"#define\s+(\w+_BASE)\s+\(\(uint32_t\)\(?\s*(0x[0-9A-Fa-f]+)\s*\)?\)", text):
        bases.setdefault(m.group(1), int(m.group(2), 16))

    names = {}
    skip = {"PA", "PB", "PC", "PD", "PE"}
    for m in re.finditer(r"#define\s+(\w+)\s+\(\(\s*(\w+)\s*\*\s*\)\s*\(?\s*(\w+)\s*(?:\+\s*(0x[0-9A-Fa-f]+))?\s*\)?\)", text):
        inst, typ, base, add = m.groups()
        if inst in skip or typ not in structs or base not in bases:
            continue
        addr0 = bases[base] + (int(add, 16) if add else 0)
        for off, size, field in structs[typ]:
            names.setdefault(addr0 + off, (size, f"{inst}.{field}"))

    core = {
        0xE000E010: (4, "SysTick.CTRL"), 0xE000E014: (4, "SysTick.LOAD"),
        0xE000E018: (4, "SysTick.VAL"), 0xE000E01C: (4, "SysTick.CALIB"),
        0xE000ED00: (4, "SCB.CPUID"), 0xE000ED04: (4, "SCB.ICSR"), 0xE000ED08: (4, "SCB.VTOR"),
        0xE000ED0C: (4, "SCB.AIRCR"), 0xE000ED10: (4, "SCB.SCR"), 0xE000ED14: (4, "SCB.CCR"),
        0xE000ED18: (4, "SCB.SHPR1"), 0xE000ED1C: (4, "SCB.SHPR2"), 0xE000ED20: (4, "SCB.SHPR3"),
        0xE000ED24: (4, "SCB.SHCSR"), 0xE000ED88: (4, "SCB.CPACR"), 0xE000EDFC: (4, "CoreDebug.DEMCR"),
        0xE0001000: (4, "DWT.CTRL"), 0xE0001004: (4, "DWT.CYCCNT"), 0xE000EF34: (4, "FPU.FPCCR"),
    }
    for k in range(2):
        core[0xE000E100 + 4 * k] = (4, f"NVIC.ISER[{k}]")
        core[0xE000E180 + 4 * k] = (4, f"NVIC.ICER[{k}]")
        core[0xE000E200 + 4 * k] = (4, f"NVIC.ISPR[{k}]")
        core[0xE000E280 + 4 * k] = (4, f"NVIC.ICPR[{k}]")
        core[0xE000E300 + 4 * k] = (4, f"NVIC.IABR[{k}]")
    for k in range(16):
        core[0xE000E400 + 4 * k] = (4, f"NVIC.IP[{4 * k}..{4 * k + 3}]")
    names.update(core)

    out = os.path.join(os.path.dirname(__file__), "..", "rslk_sim", "regnames.py")
    with open(out, "w", newline="\n") as f:
        f.write(NOTICE + "\n")
        f.write("REGS = {\n")
        for addr in sorted(names):
            size, name = names[addr]
            f.write(f"    0x{addr:08X}: ({size}, {name!r}),\n")
        f.write("}\n\n")
        f.write('''
_sorted = sorted(REGS)


def reg_name(addr):
    """Return a readable name for a peripheral address, e.g. 'P4.IFG' or 'TIMER_A0.CCR[3]+1'."""
    import bisect
    i = bisect.bisect_right(_sorted, addr) - 1
    if i >= 0:
        base = _sorted[i]
        size, name = REGS[base]
        if addr < base + size:
            return name if addr == base else f"{name}+{addr - base}"
    return f"0x{addr:08X}"
''')
    print(f"wrote {len(names)} registers to {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
